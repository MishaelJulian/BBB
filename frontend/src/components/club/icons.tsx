export type IconName = keyof typeof ICONS

/** Pixel rects for use inside a larger <svg> (the Home triptych draws them at a bigger cell size). */
export function PixelRects({ name, cell = 1, x = 0, y = 0, fill = 'currentColor' }: { name: IconName; cell?: number; x?: number; y?: number; fill?: string }) {
  const rects: React.ReactNode[] = []
  ICONS[name].forEach((row, j) =>
    [...row].forEach((c, i) => {
      if (c === '1') rects.push(<rect key={`${i}-${j}`} x={x + i * cell} y={y + j * cell} width={cell} height={cell} fill={fill} />)
    }),
  )
  return <>{rects}</>
}

export function PixelIcon({ name }: { name: IconName }) {
  return (
    <svg className="px" viewBox="0 0 12 12" fill="currentColor" shapeRendering="crispEdges" aria-hidden="true">
      <PixelRects name={name} />
    </svg>
  )
}
