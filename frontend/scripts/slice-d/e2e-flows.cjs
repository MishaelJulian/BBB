// Slice D browser flows at 390x844 against the LOCAL stack. Run: node scripts/slice-d/e2e-flows.cjs [signup|forgot|admin|session|account|all]
const L = require('./e2e-lib.cjs')
const { check, BASE } = L
const fs = require('node:fs')
const SHOTS = '/tmp/slicec/d/shots'
fs.mkdirSync(SHOTS, { recursive: true })
const want = process.argv[2] || 'all'
const on = (n) => want === 'all' || want === n
const EMAIL = `qa-new-${Date.now()}@bbb.test`
const PW = 'first-password-1'
let words1 = null

async function wordsOf(page) { return page.$$eval('[data-testid=phrase-words] li', (l) => l.map((x) => x.textContent.trim())) }

;(async () => {
  const { browser, ctx } = await L.launch()
  const errs = []
  const page = await ctx.newPage()
  L.watch(page, errs)

  if (on('signup')) {
    console.log('--- sign-up shows the phrase once')
    await page.goto(BASE + '/login')
    await page.getByRole('button', { name: 'Create an account' }).click()
    await page.fill('#email', EMAIL)
    await page.fill('#pw', PW)
    await page.locator('.consent input').check()
    await L.layout(page, 'sign-up form')
    await page.screenshot({ path: `${SHOTS}/signup.png`, fullPage: true })
    await page.locator('button[type=submit]').click()
    await page.waitForURL(/\/recovery/)
    await page.waitForSelector('[data-testid=phrase-words] li')
    words1 = await wordsOf(page)
    check('sign-up: 12 words shown on /recovery', words1.length === 12)
    check('sign-up: words not in the URL', !page.url().includes(words1[0] + ' ') && !decodeURIComponent(page.url()).includes(words1.join(' ')))
    check('sign-up: Continue disabled until the tick', await page.getByRole('button', { name: 'Continue' }).isDisabled())
    await L.layout(page, 'recovery')
    await page.screenshot({ path: `${SHOTS}/recovery.png`, fullPage: true })
    await page.getByRole('button', { name: 'Copy' }).click()
    check('copy answers', (await page.getByText(/^(Copied\.|Copy failed)/).count()) === 1)
    await page.locator('.chk input').check()
    await page.getByRole('button', { name: 'Continue' }).click()
    await page.waitForURL(/\/me/)
    check('after Continue the member lands on /me', true)
    // shown once: a reload asks nothing new and shows no words
    await page.goto(BASE + '/recovery?first=1')
    await page.waitForTimeout(2500)
    await page.screenshot({ path: `${SHOTS}/recovery-again.png` })
    check('second visit shows no words and says so', (await page.locator('[data-testid=phrase-words] li').count()) === 0 && /already made/.test(await page.textContent('body')))
    fs.writeFileSync('/tmp/slicec/d/words1.json', JSON.stringify({ email: EMAIL, words: words1 }))
    await L.clearSession(page)
  }

  if (on('forgot')) {
    const saved = JSON.parse(fs.readFileSync('/tmp/slicec/d/words1.json', 'utf8'))
    L.psql('delete from rate_limits')
    console.log('--- forgot password with the 12 words')
    await page.goto(BASE + '/forgot')
    await L.layout(page, 'forgot step 1')
    await page.screenshot({ path: `${SHOTS}/forgot1.png`, fullPage: true })
    await page.fill('#em', saved.email)
    await page.fill('#ph', saved.words.join(' '))
    await page.getByRole('button', { name: 'Continue' }).click()
    await page.waitForSelector('#np')
    check('step 2 password is hidden, Show reveals it', (await page.getAttribute('#np', 'type')) === 'password')
    await page.fill('#np', 'second-password-2')
    await page.getByRole('button', { name: 'Show' }).click()
    check('Show makes it text', (await page.getAttribute('#np', 'type')) === 'text')
    await page.getByRole('button', { name: 'Hide' }).click()
    check('Hide hides it again', (await page.getAttribute('#np', 'type')) === 'password')
    await L.layout(page, 'forgot step 2')
    await page.screenshot({ path: `${SHOTS}/forgot2.png`, fullPage: true })
    await page.getByRole('button', { name: 'Set password' }).click()
    await page.waitForSelector('[data-testid=phrase-words] li')
    const words2 = await wordsOf(page)
    check('step 3 shows a NEW 12-word phrase', words2.length === 12 && words2.join(' ') !== saved.words.join(' '))
    check('no words or password in the URL', !page.url().includes('password') && !page.url().includes(words2[0] + '%20'))
    await L.layout(page, 'forgot step 3')
    await page.locator('.chk input').check()
    await page.getByRole('button', { name: 'Continue' }).click()
    await page.waitForURL(/\/me/, { timeout: 15000 })
    check('after saving the new phrase the member is signed in on /me', true)
    fs.writeFileSync('/tmp/slicec/d/words2.json', JSON.stringify({ email: saved.email, words: words2 }))
    await L.clearSession(page)

    console.log('--- the old phrase no longer works; wrong phrases lock out')
    await page.goto(BASE + '/forgot')
    await page.fill('#em', saved.email)
    await page.fill('#ph', saved.words.join(' '))
    await page.getByRole('button', { name: 'Continue' }).click()
    await page.fill('#np', 'third-password-3')
    await page.getByRole('button', { name: 'Set password' }).click()
    await page.waitForSelector('.notice.err')
    check('old phrase refused with the generic message, back at step 1', /do not match/.test(await page.textContent('.notice.err')) && (await page.locator('#em').count()) === 1)
    const wrong = saved.words.slice().reverse().join(' ')
    let last = ''
    for (let i = 0; i < 6; i++) {
      await page.goto(BASE + '/forgot')
      await page.fill('#em', saved.email)
      await page.fill('#ph', wrong)
      await page.getByRole('button', { name: 'Continue' }).click()
      await page.fill('#np', 'another-pass-9')
      await page.getByRole('button', { name: 'Set password' }).click()
      await page.waitForSelector('.notice.err')
      last = await page.textContent('.notice.err')
      if (/Too many/.test(last)) break
    }
    check('repeated wrong phrases end in a lockout message', /Too many tries/.test(last), last)
    // the right phrase is refused while locked, with the same words as for a stranger
    L.psql('delete from rate_limits')
    await page.goto(BASE + '/forgot')
    await page.fill('#em', 'ghost-nobody@bbb.test')
    await page.fill('#ph', wrong)
    await page.getByRole('button', { name: 'Continue' }).click()
    await page.fill('#np', 'another-pass-9')
    await page.getByRole('button', { name: 'Set password' }).click()
    await page.waitForSelector('.notice.err')
    check('an unknown email gets the same generic message', /do not match/.test(await page.textContent('.notice.err')))
  }

  if (on('admin')) {
    console.log('--- admin issues a reset code; the member uses it once')
    L.psql("delete from rate_limits")
    const admin = await L.mint('qa-admin@bbb.test', 60)
    await L.setSession(page, admin)
    const memberId = L.psql("select id from members where auth_user_id = '00000000-0000-0000-0000-0000000000a3'")
    await page.goto(`${BASE}/admin/members/${memberId}`)
    await page.getByText('Issue a reset code').waitFor()
    await page.screenshot({ path: `${SHOTS}/admin-member.png`, fullPage: true })
    await L.layout(page, 'admin member page')
    await page.getByText('Issue a reset code').click()
    await page.screenshot({ path: `${SHOTS}/admin-reset-sheet1.png` })
    await page.getByRole('button', { name: 'Make the code' }).click()
    await page.waitForSelector('[data-testid=reset-code]')
    const code = (await page.textContent('[data-testid=reset-code]')).trim()
    check('code shown once in XXXXX-XXXXX form', /^[0-9A-Z]{5}-[0-9A-Z]{5}$/.test(code), code)
    await page.screenshot({ path: `${SHOTS}/admin-reset-sheet2.png` })
    await L.layout(page, 'admin reset sheet')
    await page.getByRole('button', { name: /^Copy$/ }).click()
    check('Copy answers', await page.getByRole('button', { name: 'Copied' }).count() === 1 || await page.getByText('Could not copy').count() === 1)
    const stored = L.psql("select code_hash from reset_codes order by created_at desc limit 1")
    check('only a hash is stored, never the code', stored.length === 64 && !stored.includes(code.replace('-', '')))
    await page.getByRole('button', { name: 'Done' }).click()
    check('audit row "member.reset_code" has no code in it', !L.psql("select after::text from audit_log where action = 'member.reset_code' order by id desc limit 1").includes(code.replace('-', '')))
    await page.goto(`${BASE}/admin/codes`)
    await page.getByText('Reset code').first().waitFor()
    check('Codes tool lists it as a Reset code', true)
    await page.screenshot({ path: `${SHOTS}/admin-codes.png`, fullPage: true })
    await page.goto(`${BASE}/admin/changes`)
    await page.getByText('Issued a reset code').first().waitFor()
    check('All changes lists "Issued a reset code"', true)
    await L.clearSession(page)

    await page.goto(BASE + '/forgot')
    await page.getByRole('button', { name: 'A code from an admin' }).click()
    await page.fill('#em', 'qa-other@bbb.test')
    await page.fill('#cd', code)
    await L.layout(page, 'forgot with code')
    await page.screenshot({ path: `${SHOTS}/forgot-code.png`, fullPage: true })
    await page.getByRole('button', { name: 'Continue' }).click()
    await page.fill('#np', 'code-password-1')
    await page.getByRole('button', { name: 'Set password' }).click()
    await page.waitForSelector('[data-testid=phrase-words] li')
    check('admin code works: new phrase shown', (await wordsOf(page)).length === 12)
    await page.locator('.chk input').check()
    await page.getByRole('button', { name: 'Continue' }).click()
    await page.waitForURL(/\/me/, { timeout: 15000 })
    await L.clearSession(page)
    // reuse
    await page.goto(BASE + '/forgot')
    await page.getByRole('button', { name: 'A code from an admin' }).click()
    await page.fill('#em', 'qa-other@bbb.test')
    await page.fill('#cd', code)
    await page.getByRole('button', { name: 'Continue' }).click()
    await page.fill('#np', 'code-password-2')
    await page.getByRole('button', { name: 'Set password' }).click()
    await page.waitForSelector('.notice.err')
    check('reused code refused (generic message)', /do not match/.test(await page.textContent('.notice.err')))
    // expired
    L.psql("delete from rate_limits")
    const admin2 = await L.mint('qa-admin@bbb.test', 60)
    const r = await fetch(`${BASE}/api/admin/members/${memberId}/reset-code`, { method: 'POST', headers: { authorization: `Bearer ${admin2.access_token}` } })
    const j = await r.json()
    L.psql("update reset_codes set expires_at = expires_at - 90000 where used_at is null and revoked_at is null")
    await page.goto(BASE + '/forgot')
    await page.getByRole('button', { name: 'A code from an admin' }).click()
    await page.fill('#em', 'qa-other@bbb.test')
    await page.fill('#cd', j.code)
    await page.getByRole('button', { name: 'Continue' }).click()
    await page.fill('#np', 'code-password-3')
    await page.getByRole('button', { name: 'Set password' }).click()
    await page.waitForSelector('.notice.err')
    check('expired code refused (generic message)', /do not match/.test(await page.textContent('.notice.err')))
    await page.screenshot({ path: `${SHOTS}/forgot-error.png`, fullPage: true })
  }

  await browser.close()
  console.log("errors:", errs.length ? errs.map(e=>String(e).slice(0,1500)) : "none")
  check('no console errors', errs.length === 0)
  console.log(L.fails() ? `${L.fails()} FAILED` : 'ALL PASSED')
  process.exit(L.fails() ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(2) })
