// Session lengths, Account recovery screen and attack checks. LOCAL stack only. Run: node scripts/slice-d/e2e-session.cjs
const L = require('./e2e-lib.cjs')
const { check, BASE } = L
const DAY = 86400
const UID_M = '00000000-0000-0000-0000-0000000000a1', UID_A = '00000000-0000-0000-0000-0000000000a2'
const errs = []

async function signIn(page, email, keep) {
  await L.clearSession(page)
  await page.goto(BASE + '/login')
  await page.fill('#email', email)
  await page.fill('#pw', 'correct-horse-9')
  if (keep) await page.getByLabel(/Keep me signed in/).check()
  await page.locator('button[type=submit]').click()
  await page.waitForURL((u) => !/\/login/.test(u.pathname), { timeout: 15000 })
  await page.waitForLoadState('networkidle').catch(() => {})
  await page.waitForTimeout(1500)
}
const shiftServer = (uid, days) => L.psql(`update session_prefs set started_at = started_at - ${Math.round(days * DAY)} where user_id = '${uid}'`)
const shiftClient = async (page, days) => { for (let i = 0; i < 5; i++) { try { return await shiftClient1(page, days) } catch { await page.waitForTimeout(800) } } }
const shiftClient1 = (page, days) => page.evaluate((s) => { const v = JSON.parse(localStorage.getItem('bbb_sess')); v.t -= s; localStorage.setItem('bbb_sess', JSON.stringify(v)) }, Math.round(days * DAY))
async function expired(page, path) {
  await page.goto(BASE + path)
  await page.waitForURL(/\/login\?expired=1/, { timeout: 8000 }).catch(() => {})
  await page.getByText('Your previous session has expired').waitFor({ timeout: 5000 }).catch(() => {})
  return /\/login\?expired=1/.test(page.url()) && /Your previous session has expired/.test(await page.textContent('body'))
}
;(async () => {
  const { browser, ctx } = await L.launch()
  const page = await ctx.newPage()
  L.watch(page, errs)
  L.psql('delete from rate_limits')

  console.log('--- login screen')
  await page.goto(BASE + '/login')
  check('keep-me-signed-in is off by default, with the mockup wording', !(await page.getByLabel(/Keep me signed in/).isChecked()) && /Members: 90 days instead of 30\. Admins: always 24 hours\./.test(await page.textContent('body')))
  check('the mailto is replaced by the real forgot link', (await page.locator('a[href="/forgot"]').count()) === 1 && (await page.locator('.auth a[href^="mailto"]').count() === 0))
  await L.layout(page, 'login')
  await page.screenshot({ path: '/tmp/slicec/d/shots/login.png', fullPage: true })

  console.log('--- default member: 30 days')
  L.psql('delete from session_prefs')
  await signIn(page, 'qa-member@bbb.test', false)
  check('default sign-in: keep=0 recorded', L.psql(`select keep from session_prefs where user_id='${UID_M}'`) === '0')
  shiftServer(UID_M, 29); await shiftClient(page, 29)
  await page.goto(BASE + '/me'); await page.waitForTimeout(1500)
  check('29 days: still signed in', !/\/login/.test(page.url()))
  shiftServer(UID_M, 2); await shiftClient(page, 2)
  check('31 days (server and browser): signed out with the expiry notice', await expired(page, '/me'))
  await page.screenshot({ path: '/tmp/slicec/d/shots/expired.png', fullPage: true })

  console.log('--- keep me signed in: 90 days')
  L.psql('delete from session_prefs')
  await signIn(page, 'qa-member@bbb.test', true)
  check('keep sign-in: keep=1 recorded', L.psql(`select keep from session_prefs where user_id='${UID_M}'`) === '1')
  shiftServer(UID_M, 60); await shiftClient(page, 60)
  await page.goto(BASE + '/me'); await page.waitForTimeout(1500)
  check('60 days with keep: still signed in', !/\/login/.test(page.url()))
  shiftServer(UID_M, 31); await shiftClient(page, 31)
  check('91 days with keep: signed out', await expired(page, '/me'))

  console.log('--- admin: 24 hours always, keep ignored')
  L.psql('delete from session_prefs')
  await signIn(page, 'qa-admin@bbb.test', true)
  check('admin keep is stored as 0', L.psql(`select keep from session_prefs where user_id='${UID_A}'`) === '0')
  shiftServer(UID_A, 23 / 24); await shiftClient(page, 23 / 24)
  await page.goto(BASE + '/admin'); await page.waitForTimeout(1500)
  check('23 hours: admin console opens', !/\/login/.test(page.url()))
  shiftServer(UID_A, 2 / 24); await shiftClient(page, 2 / 24)
  check('25 hours: admin signed out', await expired(page, '/admin'))

  console.log('--- browser-only check (no server call needed)')
  L.psql('delete from session_prefs')
  await signIn(page, 'qa-member@bbb.test', false)
  await shiftClient(page, 31)
  let apiCalls = 0
  page.on('request', (r) => { if (/\/api\/me$/.test(r.url())) apiCalls++ })
  check('browser alone signs out a 31-day session', await expired(page, '/me'))
  check('...without asking the server', apiCalls === 0, `calls=${apiCalls}`)

  console.log('--- a token refresh cannot extend the session')
  L.psql('delete from session_prefs')
  await signIn(page, 'qa-member@bbb.test', false)
  shiftServer(UID_M, 31)
  // make the stored access token look stale so supabase-js refreshes it (the stub keeps the original amr timestamp)
  await page.evaluate(() => { const k = 'sb-127-auth-token'; const v = JSON.parse(localStorage.getItem(k)); v.expires_at = 1; localStorage.setItem(k, JSON.stringify(v)); localStorage.removeItem('bbb_sess') })
  await page.goto(BASE + '/me'); await page.waitForTimeout(2500)
  check('refreshed token of a 31-day-old session is refused by the server', /\/login/.test(page.url()) || /Sign in/.test(await page.textContent('body')))
  const st = await fetch(`${BASE}/api/me`, { headers: { authorization: 'Bearer ' + (await L.mint('qa-member@bbb.test', 0)).access_token } })
  check('(control) a brand new sign-in is accepted', st.status === 200)

  console.log('--- Account: recovery phrase')
  L.psql('delete from session_prefs'); L.psql('delete from rate_limits')
  await signIn(page, 'qa-member@bbb.test', false)
  await page.goto(BASE + '/account'); await page.getByText('Recovery phrase').first().waitFor()
  check('Two-factor is not shown (backlog)', (await page.getByText(/two-factor/i).count()) === 0)
  await page.screenshot({ path: '/tmp/slicec/d/shots/account.png', fullPage: true })
  await page.goto(BASE + '/account?s=recovery'); await page.waitForSelector('#rp')
  await L.layout(page, 'account recovery')
  await page.fill('#rp', 'wrong-password-x')
  await page.getByRole('button', { name: 'Make a new phrase' }).click()
  await page.waitForSelector('.msg2.bad')
  check('wrong password: no phrase made', /not right/.test(await page.textContent('.msg2.bad')) && (await page.locator('[data-testid=phrase-words]').count()) === 0)
  await page.fill('#rp', 'correct-horse-9')
  await page.getByRole('button', { name: 'Make a new phrase' }).click()
  await page.waitForSelector('[data-testid=phrase-words] li')
  check('right password: new 12 words shown', (await page.locator('[data-testid=phrase-words] li').count()) === 12)
  await page.screenshot({ path: '/tmp/slicec/d/shots/account-phrase.png', fullPage: true })
  await page.locator('.chk input').check()
  await page.getByRole('button', { name: 'Done' }).click()
  await page.waitForURL(/\/account$/)
  check('Done returns to Account', true)

  console.log('--- attack checks (HTTP)')
  L.psql('delete from rate_limits')
  const mem = await L.mint('qa-member@bbb.test', 0), adm = await L.mint('qa-admin@bbb.test', 0), oth = await L.mint('qa-other@bbb.test', 0)
  const aartiId = L.psql("select id from members where auth_user_id = '00000000-0000-0000-0000-0000000000a3'")
  const call = async (method, path, tok, body) => (await fetch(BASE + path, { method, headers: { 'content-type': 'application/json', ...(tok ? { authorization: 'Bearer ' + tok.access_token } : {}) }, body: body ? JSON.stringify(body) : undefined })).status
  check('no token: issue reset code 401', (await call('POST', `/api/admin/members/${aartiId}/reset-code`, null)) === 401)
  check('member cannot issue a reset code (403)', (await call('POST', `/api/admin/members/${aartiId}/reset-code`, mem)) === 403)
  check('member cannot list codes (403)', (await call('GET', '/api/admin/codes', mem)) === 403)
  check('member cannot revoke a code (403)', (await call('POST', '/api/admin/codes/00000000-0000-0000-0000-000000000000/revoke', mem)) === 403)
  const unlinked = L.psql("select id from members where auth_user_id is null limit 1")
  check('admin: unlinked member gets 409, no code', (await call('POST', `/api/admin/members/${unlinked}/reset-code`, adm)) === 409)
  check('admin: linked member 200', (await call('POST', `/api/admin/members/${aartiId}/reset-code`, adm)) === 200)
  check('no token: recovery status/post 401', (await call('GET', '/api/me/recovery', null)) === 401 && (await call('POST', '/api/me/recovery', null, {})) === 401)
  check('session/start without token 401', (await call('POST', '/api/session/start', null, { keep: true })) === 401)
  // a stolen member token cannot read another member\'s secrets: there is no route that returns a phrase or a code, and the list is admin only
  const r = await (await fetch(`${BASE}/api/admin/codes`, { headers: { authorization: 'Bearer ' + adm.access_token } })).text()
  check('code list never contains a code or hash', !/code_hash|[0-9A-Z]{5}-[0-9A-Z]{5}/.test(r))
  // password brute force on regenerate: 5 tries per 10 minutes
  let last = 0
  for (let i = 0; i < 7; i++) last = await call('POST', '/api/me/recovery', oth, { password: 'nope' + i })
  check('wrong-password tries on "new phrase" end in 429', last === 429, `last=${last}`)
  const logged = L.psql("select count(*) from audit_log where action like 'auth.%'")
  check('auth events are in the audit log', Number(logged) > 0, logged)

  await browser.close()
  console.log('errors:', errs.length ? errs : 'none')
  check('no console errors', errs.length === 0)
  console.log(L.fails() ? `${L.fails()} FAILED` : 'ALL PASSED')
  process.exit(L.fails() ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(2) })
